#!/usr/bin/env node
/**
 * Design Partner Outreach Email Generator
 * Generates 900 customized outreach emails across 9 verticals.
 *
 * Usage:  node generate-dp-emails.cjs
 * Output: ../DESIGN-PARTNER-OUTREACH.md
 */

const fs = require('fs');
const path = require('path');

// ─── Load all vertical data files ────────────────────────────────────────────
const verticals = [
  { file: 'dp-sport.cjs',        label: 'Sport',                        icon: '🏟️' },
  { file: 'dp-healthcare.cjs',   label: 'Healthcare',                   icon: '🏥' },
  { file: 'dp-finance.cjs',      label: 'Finance',                      icon: '🏦' },
  { file: 'dp-defence.cjs',      label: 'Defence',                      icon: '🛡️' },
  { file: 'dp-energy.cjs',       label: 'Energy / Utilities',           icon: '⚡' },
  { file: 'dp-insurance.cjs',    label: 'Insurance',                    icon: '📋' },
  { file: 'dp-government.cjs',   label: 'Government / Public Sector',   icon: '🏛️' },
  { file: 'dp-legal.cjs',        label: 'Legal / Professional Services', icon: '⚖️' },
  { file: 'dp-technology.cjs',   label: 'Technology / Enterprise SaaS',  icon: '💻' },
];

// ─── Regulation context per vertical ─────────────────────────────────────────
const verticalRegulations = {
  sport:       'FIFA AI Ethics Framework, World Anti-Doping Agency regulations, and emerging sports integrity legislation',
  healthcare:  'HIPAA, FDA AI/ML guidance, EU MDR, and the EU AI Act (high-risk classification for medical AI)',
  finance:     'DORA, EU AI Act, ECOA, CFPB AI guidance, SEC AI advisory, and Basel III operational risk requirements',
  defence:     'DoD AI Ethics Principles, ITAR, EAR, NATO DIANA standards, and sovereign deployment mandates',
  energy:      'TNFD, ISSB S1/S2, ECB Climate Risk Guide, NERC CIP, and EU AI Act environmental risk provisions',
  insurance:   'NAIC AI Model Bulletin, EU AI Act (high-risk for insurance pricing), Solvency II, and state insurance AI regulations',
  government:  'OMB AI Guidance (M-24-10), EU AI Act (high-risk for public services), NIST AI RMF, and federal procurement AI mandates',
  legal:       'ABA Model Rules on AI, EU AI Act (high-risk for judicial AI), court e-discovery standards, and legal professional conduct rules',
  technology:  'EU AI Act, SOC 2 AI controls, ISO 42001, NIST AI RMF, and enterprise customer AI governance requirements',
};

// ─── Email generation ────────────────────────────────────────────────────────
function generateEmail(company) {
  const v = company.vertical;
  const regs = verticalRegulations[v] || 'emerging AI governance regulations';

  const subject = `Design partnership — AI decision evidence for ${company.aiUseCase.toLowerCase().split(' ').slice(0, 6).join(' ')}`;

  const body = `Hi ${company.contact.split(' ')[0]},

I'm Stuart Rainey, founder of Datacendia (datacendia.com). We build AI decision evidence infrastructure — proving how and why every AI-assisted decision was made, with audit-grade evidence exportable for regulators and stakeholders.

**Why this matters for ${company.company}:** ${company.painPoint}${company.regulatoryHook ? ' ' + company.regulatoryHook : ''} Regulations including ${regs} are converging on one requirement: verifiable evidence of AI decision-making.

**The offer:** 90-day design partnership at no cost. Datacendia layers onto your existing AI pipeline and produces cryptographic evidence for every AI decision — decision rationale, fairness metrics, and compliance documentation. You get audit-ready AI governance. We get product feedback from a leader in ${company.subCategory.toLowerCase()}.

**What's built:** 205K+ passing tests, 156 API endpoints, live at app.datacendia.com. Zero-copy architecture — connects to your existing infrastructure without moving data. Sovereign deployment available (on-prem, air-gapped, or private cloud).

Would a 20-minute walkthrough make sense? Happy to demo how Datacendia integrates with ${company.aiUseCase.toLowerCase()}.

Best,
Stuart Rainey
Founder & CEO, Datacendia
contact@datacendia.com | datacendia.com | app.datacendia.com`;

  return { subject, body };
}

// ─── Main ────────────────────────────────────────────────────────────────────
function main() {
  const allCompanies = [];

  for (const v of verticals) {
    const filePath = path.join(__dirname, v.file);
    if (!fs.existsSync(filePath)) {
      console.warn(`  ⚠ Skipping ${v.file} (not found)`);
      continue;
    }
    const data = require(filePath);
    console.log(`  ✓ ${v.label}: ${data.length} companies`);
    for (const c of data) {
      c.vertical = c.vertical || v.file.replace('dp-', '').replace('.cjs', '');
      allCompanies.push({ ...c, _verticalLabel: v.label, _verticalIcon: v.icon });
    }
  }

  console.log(`\nTotal: ${allCompanies.length} design partner companies\n`);

  // Build markdown
  const lines = [];
  lines.push('# Datacendia — Design Partner Outreach (900 Companies)');
  lines.push('');
  lines.push('> Auto-generated by `design-partners/generate-dp-emails.cjs`');
  lines.push('> Each email offers a **90-day free pilot** in exchange for product feedback and a case study.');
  lines.push('');
  lines.push('## Table of Contents');
  lines.push('');

  // Group by vertical
  const grouped = {};
  for (const c of allCompanies) {
    const key = c._verticalLabel;
    if (!grouped[key]) grouped[key] = { icon: c._verticalIcon, companies: [] };
    grouped[key].companies.push(c);
  }

  let companyNum = 0;
  for (const [label, group] of Object.entries(grouped)) {
    lines.push(`- **${group.icon} ${label}** (${group.companies.length} companies)`);
  }
  lines.push('');

  // Generate emails per vertical
  for (const [label, group] of Object.entries(grouped)) {
    lines.push('---');
    lines.push('');
    lines.push(`# ${group.icon} ${label}`);
    lines.push('');

    // Contact summary table
    lines.push('| # | Company | Contact | Title | Method | AI Use Case |');
    lines.push('|---|---------|---------|-------|--------|-------------|');
    for (let i = 0; i < group.companies.length; i++) {
      const c = group.companies[i];
      const method = c.contactEmail
        ? (c.contactEmail.startsWith('http') ? `[LinkedIn](${c.contactEmail})` : `📧 ${c.contactEmail}`)
        : (c.contactUrl ? `🌐 [Form](${c.contactUrl})` : '🔍 Research');
      lines.push(`| ${i + 1} | **${c.company}** | ${c.contact} | ${c.contactTitle} | ${method} | ${c.aiUseCase} |`);
    }
    lines.push('');

    // Individual emails
    for (let i = 0; i < group.companies.length; i++) {
      const c = group.companies[i];
      companyNum++;
      const email = generateEmail(c);
      const method = c.contactEmail
        ? (c.contactEmail.startsWith('http') ? `LinkedIn: ${c.contactEmail}` : `Email: ${c.contactEmail}`)
        : (c.contactUrl ? `Form: ${c.contactUrl}` : 'Contact: Research needed');

      lines.push(`### ${companyNum}. ${c.company}`);
      lines.push(`**Contact:** ${c.contact} — ${c.contactTitle}`);
      lines.push(`**${method}**`);
      lines.push(`**HQ:** ${c.hq}`);
      lines.push('');
      lines.push(`**Subject:** ${email.subject}`);
      lines.push('');
      lines.push(email.body);
      lines.push('');
      lines.push('---');
      lines.push('');
    }
  }

  // Write output
  const outPath = path.join(__dirname, '..', 'DESIGN-PARTNER-OUTREACH.md');
  fs.writeFileSync(outPath, lines.join('\n'), 'utf-8');
  console.log(`Written to ${outPath}`);
  console.log(`Total emails generated: ${companyNum}`);
}

main();
